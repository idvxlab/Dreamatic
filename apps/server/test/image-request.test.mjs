import test from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {requestImage,retryImage,ImageRequestError} from '../dist/image-request.js';
const base={apiKey:'test-key',model:'fixture',prompt:'test image',size:'1024x768',responseFormat:'b64_json',timeoutMs:3000,bodyIdleTimeoutMs:3000};
async function server(t,handler){const app=createServer(handler);await new Promise(resolve=>app.listen(0,'127.0.0.1',resolve));t.after(()=>new Promise(resolve=>{app.close(resolve);app.closeAllConnections()}));return `http://127.0.0.1:${app.address().port}`;}
const payload=JSON.stringify({data:[{b64_json:Buffer.from('generated bytes').toString('base64')}],usage:{total_tokens:12}});

test('dedicated image transport waits for configured headers and preserves payload/usage',async t=>{
 const url=await server(t,async(req,res)=>{assert.equal(req.headers.authorization,'Bearer test-key');await new Promise(r=>setTimeout(r,80));res.setHeader('Content-Type','application/json');res.end(payload)});
 const result=await requestImage({...base,url,bodyIdleTimeoutMs:40,signal:new AbortController().signal});
 assert.equal(result.bytes.toString(),'generated bytes');assert.deepEqual(result.usage,{total_tokens:12});
});
test('total deadline and explicit cancellation are distinct, bounded and release connections',async t=>{
 const url=await server(t,()=>{});
 await assert.rejects(requestImage({...base,url,timeoutMs:40,signal:new AbortController().signal}),error=>error.failure?.code==='IMAGE_TOTAL_TIMEOUT');
 const controller=new AbortController();setTimeout(()=>controller.abort(),25);
 await assert.rejects(requestImage({...base,url,signal:controller.signal}),error=>error.name==='AbortError');
});
test('download shares the total deadline and never receives generation credentials',async t=>{
 let url;
 url=await server(t,(req,res)=>{if(req.url==='/image'){assert.equal(req.headers.authorization,undefined);return; }res.setHeader('Content-Type','application/json');res.end(JSON.stringify({data:[{url:url+'/image'}]}));});
 await assert.rejects(requestImage({...base,url,timeoutMs:100,signal:new AbortController().signal}),error=>error.failure?.code==='IMAGE_TOTAL_TIMEOUT'&&error.failure.phase==='download');
});
test('HTTP errors retain status and retry policy without exposing remote error bodies',async t=>{
 const url=await server(t,(req,res)=>{res.writeHead(Number(req.url.slice(1)),{'Retry-After':'5'});res.end('secret provider body, token=test-key');});
 for(const status of [400,401,403,429,502])await assert.rejects(requestImage({...base,url:url+'/'+status,signal:new AbortController().signal}),error=>{
  assert.equal(error.failure.status,status);assert.equal(error.failure.retryable,status===429||status===502);assert.equal(error.failure.retryAfterMs,5000);assert.ok(!error.message.includes('test-key'));return true;
 });
});
test('retry attempts and backoff are bounded; terminal errors and cancellation do not loop',async()=>{
 const controller=new AbortController(),delays=[];let calls=0;
 const failure={message:'temporary error',code:'HTTP_502',retryable:true,phase:'generation'};
 const result=await retryImage(async()=>{calls++;throw new ImageRequestError(failure)},{maxAttempts:3,signal:controller.signal,sleep:async ms=>{delays.push(ms)}});
 assert.equal(calls,3);assert.equal(result.ok,false);assert.equal(result.attempts,3);assert.deepEqual(delays,[2000,4000]);
 calls=0;const terminal=await retryImage(async()=>{calls++;throw new ImageRequestError({...failure,retryable:false,code:'HTTP_401'})},{maxAttempts:3,signal:controller.signal});
 assert.equal(calls,1);assert.equal(terminal.ok,false);
 await assert.rejects(retryImage(async()=>{throw new Error('Disk failure')},{maxAttempts:3,signal:controller.signal}),/Disk failure/);
 calls=0;await assert.rejects(retryImage(async()=>{calls++;throw new ImageRequestError(failure)},{maxAttempts:3,signal:controller.signal,sleep:async()=>controller.abort()}),error=>error.name==='AbortError');assert.equal(calls,1);
});
test('transport cause codes remain available for DNS and connection diagnostics',async t=>{
 const url=await server(t,(req,res)=>req.socket.destroy());
 await assert.rejects(requestImage({...base,url,signal:new AbortController().signal}),error=>error instanceof ImageRequestError&&/^UND_ERR_|ECONN/.test(error.failure.code));
});

test('body idle timeout retains its transport cause before the total deadline',async t=>{
 const url=await server(t,(req,res)=>{res.writeHead(200,{'Content-Type':'application/json'});res.write('{"data":[');});
 await assert.rejects(requestImage({...base,url,timeoutMs:5000,bodyIdleTimeoutMs:30,signal:new AbortController().signal}),error=>error.failure?.code==='UND_ERR_BODY_TIMEOUT');
});
test('reported generation usage survives a later download failure and is not fabricated',async t=>{
 let url;const usage=[];
 url=await server(t,(req,res)=>{if(req.url==='/image'){res.writeHead(502);res.end();return;}res.setHeader('Content-Type','application/json');res.end(JSON.stringify({data:[{url:url+'/image'}],usage:{total_tokens:42}}));});
 await assert.rejects(requestImage({...base,url,signal:new AbortController().signal,onUsage:async value=>{usage.push(value)}}),error=>error.failure?.status===502&&error.failure.phase==='download');
 assert.deepEqual(usage,[{total_tokens:42}]);
});

test('response byte limit accepts the exact boundary and rejects advertised or chunked JSON overflow without retry',async t=>{
 const limit=Buffer.byteLength(payload);let calls=0;
 const url=await server(t,(req,res)=>{calls++;if(req.url==='/chunked'){res.writeHead(200);res.write(payload.slice(0,10));res.end(payload.slice(10));}else res.end(payload);});
 assert.equal((await requestImage({...base,url,maxResponseBytes:limit,signal:new AbortController().signal})).bytes.toString(),'generated bytes');
 for(const path of ['/','/chunked']){
  const before=calls;
  const result=await retryImage(()=>requestImage({...base,url:url+path,maxResponseBytes:limit-1,signal:new AbortController().signal}),{maxAttempts:3,signal:new AbortController().signal});
  assert.equal(result.ok,false);assert.equal(result.error.code,'IMAGE_RESPONSE_TOO_LARGE');assert.equal(result.error.phase,'generation');assert.equal(result.error.retryable,false);assert.equal(calls-before,1);
 }
});
test('image download uses the same bound, including streaming bodies without Content-Length',async t=>{
 let url;const limit=256,usage=[];
 url=await server(t,(req,res)=>{
  if(req.url.startsWith('/image')){if(req.url==='/image-exact')return res.end(Buffer.alloc(limit));res.writeHead(200);res.write(Buffer.alloc(200));res.end(Buffer.alloc(200));return;}
  res.end(JSON.stringify({data:[{url:url+(req.url==='/exact'?'/image-exact':'/image-large')}],usage:{total_tokens:5}}));
 });
 assert.equal((await requestImage({...base,url:url+'/exact',maxResponseBytes:limit,signal:new AbortController().signal})).bytes.length,limit);
 await assert.rejects(requestImage({...base,url,maxResponseBytes:limit,signal:new AbortController().signal,onUsage:async v=>usage.push(v)}),error=>error.failure?.code==='IMAGE_RESPONSE_TOO_LARGE'&&error.failure.phase==='download'&&!error.failure.retryable);
 assert.deepEqual(usage,[{total_tokens:5}]);
});

